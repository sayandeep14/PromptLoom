package deps

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"

	"github.com/BurntSushi/toml"
)

const PackLockFilename = "loompack.lock"

// PackLockEntry records one installed pack in loompack.lock.
type PackLockEntry struct {
	Slug       string   `toml:"slug"`
	Version    string   `toml:"version"`
	RequiredBy []string `toml:"required_by,omitempty"`
}

// PackLock is the in-memory representation of loompack.lock.
type PackLock struct {
	Packs []PackLockEntry `toml:"pack"`
}

// PackLockPath returns the absolute path of loompack.lock for the given project root.
func PackLockPath(cwd string) string {
	return filepath.Join(cwd, PackLockFilename)
}

// ReadPackLock parses loompack.lock from cwd. Returns an empty PackLock (not an
// error) when the file does not exist yet.
func ReadPackLock(cwd string) (*PackLock, error) {
	path := PackLockPath(cwd)
	if _, err := os.Stat(path); os.IsNotExist(err) {
		return &PackLock{}, nil
	}
	var pl PackLock
	if _, err := toml.DecodeFile(path, &pl); err != nil {
		return nil, fmt.Errorf("loompack.lock: %w", err)
	}
	return &pl, nil
}

// WritePackLock serialises pl to loompack.lock in cwd.
func WritePackLock(pl *PackLock, cwd string) error {
	// Stable order: sort by slug.
	sort.Slice(pl.Packs, func(i, j int) bool {
		return pl.Packs[i].Slug < pl.Packs[j].Slug
	})
	var buf bytes.Buffer
	buf.WriteString("# loompack.lock — generated by loom install; do not edit manually\n\n")
	if err := toml.NewEncoder(&buf).Encode(pl); err != nil {
		return err
	}
	return os.WriteFile(PackLockPath(cwd), buf.Bytes(), 0o644)
}

// Upsert adds or updates the entry for slug in pl.
func (pl *PackLock) Upsert(entry PackLockEntry) {
	for i, p := range pl.Packs {
		if p.Slug == entry.Slug {
			pl.Packs[i] = entry
			return
		}
	}
	pl.Packs = append(pl.Packs, entry)
}

// Find returns the entry for slug, or nil if not present.
func (pl *PackLock) Find(slug string) *PackLockEntry {
	for i := range pl.Packs {
		if pl.Packs[i].Slug == slug {
			return &pl.Packs[i]
		}
	}
	return nil
}
